// Pick ANY benchmarked ratio and watch this company vs the peer median across every
// year on file — not just EBITDA margin. This is the "are we negotiating with a
// leader or a laggard, and is the gap widening?" view.
function PeerGapTrend({ benchmarks }: { benchmarks: Detail["peers"]["benchmarks"] }) {
  const METRICS: { k: string; label: string; unit: string; higherBetter: boolean }[] = [
    { k: "ebitdaMargin", label: "EBITDA margin", unit: "%", higherBetter: true },
    { k: "netMargin", label: "Net margin", unit: "%", higherBetter: true },
    { k: "grossMargin", label: "Gross margin", unit: "%", higherBetter: true },
    { k: "roce", label: "RoCE", unit: "%", higherBetter: true },
    { k: "roe", label: "RoE", unit: "%", higherBetter: true },
    { k: "revenueGrowth", label: "Revenue growth", unit: "%", higherBetter: true },
    { k: "debtorDays", label: "Collection days", unit: "d", higherBetter: false },
    { k: "payableDays", label: "Payment days", unit: "d", higherBetter: false },
    { k: "cashConversion", label: "Cash cycle", unit: "d", higherBetter: false },
    { k: "debtEquity", label: "Debt / equity", unit: "x", higherBetter: false },
    { k: "currentRatio", label: "Current ratio", unit: "x", higherBetter: true },
  ].filter((m) => benchmarks.some((b) => n(b.self[m.k]) != null || n(b.median[m.k]) != null));
  const [mk, setMk] = useState(METRICS[0]?.k ?? "ebitdaMargin");
  const met = METRICS.find((m) => m.k === mk) ?? METRICS[0];
  const asc = [...benchmarks].reverse(); // oldest → newest
  const fmt = met.unit === "%" ? (v: number) => `${v}%` : met.unit === "d" ? (v: number) => `${Math.round(v)} d` : (v: number) => v.toFixed(2);
  const self = asc.map((b) => n(b.self[mk]));
  const median = asc.map((b) => n(b.median[mk]));
  const lastSelf = [...self].reverse().find((v) => v != null) ?? null;
  const lastMed = [...median].reverse().find((v) => v != null) ?? null;
  const ahead = lastSelf != null && lastMed != null ? (met.higherBetter ? lastSelf > lastMed : lastSelf < lastMed) : null;
  return (
    <Card title="This company vs the peer median — over time" sub="pick any metric · every benchmarked year on file" accent={C.indigo} className="lg:col-span-2">
      <div className="mb-3 flex flex-wrap gap-1.5">
        {METRICS.map((m) => <button key={m.k} onClick={() => setMk(m.k)} className={`rounded-lg px-2.5 py-1 text-xs font-semibold transition ${mk === m.k ? "bg-indigo-600 text-white" : "bg-slate-100 text-slate-600 hover:bg-slate-200"}`}>{m.label}</button>)}
      </div>
      {ahead != null && (
        <div className={`mb-3 inline-flex items-center gap-1.5 rounded-lg px-2.5 py-1 text-xs font-medium ${ahead ? "bg-emerald-50 text-emerald-700 ring-1 ring-emerald-200" : "bg-rose-50 text-rose-700 ring-1 ring-rose-200"}`}>
          {ahead ? "✓ Ahead of peers" : "▼ Behind peers"} on {met.label.toLowerCase()} — {fmt(lastSelf as number)} vs {fmt(lastMed as number)} median
        </div>
      )}
      <MultiLine xLabels={asc.map((b) => b.year)} valueLabel={fmt} height={260}
        series={[{ name: "This company", color: TEAL, points: self }, { name: "Peer median", color: C.slate, points: median }]} />
    </Card>
  );
}

