// Cost structure as a 100%-stacked bar per year — shows, at a glance, how much of
// each sales rupee is eaten by materials/people/overheads and how much is left as
// profit. A widening green (profit) band is a direct "they can give on price" cue.
function CostMix({ fin }: { fin: FinRow[] }) {
  // Was a native title="" tooltip on each segment — slow to appear and easy to
  // miss, which is exactly what the client hit ("I hover and nothing happens").
  // Now hovering any row lifts a proper panel that breaks the whole ₹100 down.
  const [hover, setHover] = useState<string | null>(null);
  const parts = [
    { k: "Materials", c: "#0d9488", get: (f: FinRow) => (n(f.materialCost) ?? 0) + (n(f.purchases) ?? 0) },
    { k: "People", c: "#6366f1", get: (f: FinRow) => n(f.employeeCost) ?? 0 },
    { k: "Other spend (ads, freight, overhead)", c: "#f59e0b", get: (f: FinRow) => n(f.otherExpense) ?? 0 },
    { k: "Their profit", c: "#10b981", get: (f: FinRow) => Math.max(0, n(f.ebitda) ?? 0) },
  ];
  const rows = fin.map((f) => {
    const vals = parts.map((p) => p.get(f));
    const tot = vals.reduce((a, b) => a + b, 0) || 1;
    return { fy: f.fy, segs: parts.map((p, i) => ({ ...p, pct: (vals[i] / tot) * 100, rupees: Math.round((vals[i] / tot) * 100) })) };
  });
  return (
    <div>
      <div className="mb-2 flex flex-wrap gap-x-3 gap-y-1 text-[11px]">
        {parts.map((p) => <span key={p.k} className="inline-flex items-center gap-1 text-slate-600"><span className="h-2.5 w-2.5 rounded-sm" style={{ background: p.c }} />{p.k}</span>)}
      </div>
      <div className="space-y-1">
        {rows.map((r) => (
          <div key={r.fy} className="relative flex items-center gap-2" onMouseEnter={() => setHover(r.fy)} onMouseLeave={() => setHover(null)}>
            <span className="w-9 shrink-0 text-[10px] font-semibold text-slate-500">{r.fy}</span>
            <div className={`flex h-5 flex-1 cursor-default overflow-hidden rounded ring-1 transition ${hover === r.fy ? "ring-slate-400" : "ring-slate-200"}`}>
              {r.segs.map((s) => s.pct > 0.5 && <div key={s.k} style={{ width: `${s.pct}%`, background: s.c, opacity: hover && hover !== r.fy ? 0.5 : 1 }} />)}
            </div>
            <span className="w-9 shrink-0 text-right text-[10px] font-bold text-emerald-600">{Math.round(r.segs[3].pct)}%</span>
            {hover === r.fy && (
              <div className="absolute right-12 top-full z-20 mt-1 w-60 rounded-xl bg-slate-900 p-2.5 text-white shadow-xl">
                <div className="mb-1.5 text-[11px] font-bold text-slate-300">{r.fy} — every ₹100 of sales</div>
                <div className="space-y-1">
                  {r.segs.map((s) => (
                    <div key={s.k} className="flex items-center gap-2 text-xs">
                      <span className="h-2.5 w-2.5 shrink-0 rounded-sm" style={{ background: s.c }} />
                      <span className="flex-1 text-slate-200">{s.k}</span>
                      <span className="font-bold tabular-nums">₹{s.rupees}</span>
                    </div>
                  ))}
                </div>
              </div>
            )}
          </div>
        ))}
      </div>
    </div>
  );
}
function FinTable({ fin }: { fin: FinRow[] }) {
  // dir: +1 = higher is better, -1 = lower is better, 0 = neutral (no colour)
  type R = { label: string; get: (f: FinRow) => number | null; fmt: (v: number | null) => string; dir: number; indent?: boolean };
  const x2 = (v: number | null) => (v == null ? "—" : v.toFixed(2));
  const add = (a: number | null | undefined, b: number | null | undefined) => { const x = n(a), y = n(b); return x == null && y == null ? null : (x ?? 0) + (y ?? 0); };
  const sections: { title: string; rows: R[] }[] = [
    { title: "Income statement", rows: [
      { label: "Revenue", get: (f) => f.revenue, fmt: cr, dir: 1 },
      { label: "Material + purchases", get: (f) => add(f.materialCost, f.purchases), fmt: cr, dir: 0, indent: true },
      { label: "Employee cost", get: (f) => n(f.employeeCost), fmt: cr, dir: 0, indent: true },
      { label: "Other expenses", get: (f) => n(f.otherExpense), fmt: cr, dir: 0, indent: true },
      { label: "EBITDA", get: (f) => f.ebitda, fmt: cr, dir: 1 },
      { label: "Depreciation", get: (f) => n(f.depreciation), fmt: cr, dir: 0, indent: true },
      { label: "Interest", get: (f) => n(f.interest), fmt: cr, dir: -1, indent: true },
      { label: "Tax", get: (f) => n(f.tax), fmt: cr, dir: 0, indent: true },
      { label: "Net profit (PAT)", get: (f) => f.pat, fmt: cr, dir: 1 },
    ] },
    { title: "Balance sheet", rows: [
      { label: "Fixed assets", get: (f) => f.bs.tangibleAssets, fmt: cr, dir: 0 },
      { label: "Inventory", get: (f) => f.bs.inventory, fmt: cr, dir: 0 },
      { label: "Receivables", get: (f) => f.bs.receivables, fmt: cr, dir: 0 },
      { label: "Cash & equivalents", get: (f) => f.bs.cash, fmt: cr, dir: 1 },
      { label: "Total assets", get: (f) => f.bs.totalAssets, fmt: cr, dir: 0 },
      { label: "Equity / net worth", get: (f) => f.bs.equity, fmt: cr, dir: 1 },
      { label: "Total debt", get: (f) => f.bs.debt, fmt: cr, dir: -1 },
      { label: "Payables", get: (f) => f.bs.payables, fmt: cr, dir: 0 },
    ] },
    { title: "Cash flow", rows: [
      { label: "Operating", get: (f) => f.cf.operating, fmt: cr, dir: 1 },
      { label: "Investing", get: (f) => f.cf.investing, fmt: cr, dir: 0 },
      { label: "Financing", get: (f) => f.cf.financing, fmt: cr, dir: 0 },
    ] },
    { title: "Key ratios", rows: [
      { label: "Operating margin", get: (f) => f.r.ebitdaMargin, fmt: pct, dir: 1 },
      { label: "Net margin", get: (f) => f.r.netMargin, fmt: pct, dir: 1 },
      { label: "Margin after materials", get: (f) => f.r.grossMargin, fmt: pct, dir: 1 },
      { label: "Return on capital", get: (f) => f.r.roce, fmt: pct, dir: 1 },
      { label: "Return on equity", get: (f) => f.r.roe, fmt: pct, dir: 1 },
      { label: "Debt / equity", get: (f) => f.r.debtEquity, fmt: x2, dir: -1 },
      { label: "Interest cover", get: (f) => f.r.interestCover, fmt: xN, dir: 1 },
      { label: "Current ratio", get: (f) => f.r.currentRatio, fmt: x2, dir: 1 },
      { label: "Quick ratio", get: (f) => f.r.quickRatio, fmt: x2, dir: 1 },
      { label: "Collects in", get: (f) => f.r.debtorDays, fmt: days, dir: -1 },
      { label: "Pays in", get: (f) => f.r.payableDays, fmt: days, dir: 0 },
      { label: "Inventory days", get: (f) => f.r.inventoryDays, fmt: days, dir: -1 },
      { label: "Cash cycle", get: (f) => f.r.cashConversion, fmt: days, dir: -1 },
    ] },
  ];
  // Now returns a cell background tint too, not just text colour — the client
  // asked to see the whole cell shade green when a number improved, red when it
  // worsened. Kept subtle (50-weight) so a wall of figures stays readable.
  const move = (r: R, i: number): { cls: string; bg: string; arrow: string } => {
    if (r.dir === 0 || i === 0) return { cls: "text-slate-800", bg: "", arrow: "" };
    const v = r.get(fin[i]), p = r.get(fin[i - 1]);
    if (v == null || p == null) return { cls: "text-slate-800", bg: "", arrow: "" };
    const chg = p === 0 ? (v > 0 ? 1 : v < 0 ? -1 : 0) : (v - p) / Math.abs(p);
    if (Math.abs(chg) < 0.02) return { cls: "text-slate-400", bg: "", arrow: "" };       // stable
    const better = r.dir === 1 ? chg > 0 : chg < 0;
    return better
      ? { cls: "text-emerald-700", bg: "bg-emerald-50", arrow: v > p ? " ▲" : " ▼" }
      : { cls: "text-rose-600", bg: "bg-rose-50", arrow: v > p ? " ▲" : " ▼" };
  };
  return (
    <div className="overflow-x-auto">
      <table className={`${TBL} min-w-[760px]`}>
        <thead>
          <tr className="text-left">
            <th className="sticky left-0 z-10 bg-white px-3 py-2 text-xs font-bold uppercase tracking-wider text-slate-500">Metric</th>
            {fin.map((f) => <th key={f.fy} className="border-b-2 border-teal-500/40 bg-teal-50/60 px-3 py-2 text-right font-mono text-xs font-bold text-teal-800">{f.fy}</th>)}
          </tr>
        </thead>
        <tbody>
          {sections.map((sec) => (
            <Fragment key={sec.title}>
              <tr><td colSpan={fin.length + 1} className="sticky left-0 bg-slate-100/80 px-3 py-1 text-[11px] font-bold uppercase tracking-wider text-slate-500">{sec.title}</td></tr>
              {sec.rows.map((r) => (
                <tr key={r.label} className="border-t border-slate-100 hover:bg-slate-50/70">
                  <td className={`sticky left-0 z-10 bg-white px-3 py-1.5 ${r.indent ? "pl-6 font-normal text-slate-500" : "font-semibold text-slate-700"}`}>{r.label}</td>
                  {fin.map((f, i) => { const m = move(r, i); return <td key={f.fy} className={`whitespace-nowrap px-3 py-1.5 text-right tabular-nums font-medium ${m.cls} ${m.bg}`}>{r.fmt(r.get(f))}<span className="text-[9px]">{m.arrow}</span></td>; })}
                </tr>
              ))}
            </Fragment>
          ))}
        </tbody>
      </table>
      <div className="mt-2 flex flex-wrap gap-x-4 gap-y-1 px-1 text-[11px] text-slate-400">
        <span><b className="text-emerald-600">▲ green</b> = better than the year before</span>
        <span><b className="text-rose-500">▼ red</b> = worse</span>
        <span><b className="text-slate-400">grey</b> = about the same</span>
      </div>
    </div>
  );
}

