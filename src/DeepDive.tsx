/* ---- financial-health score (0-100) + category alternatives (#2) ----
   Blends everything we hold into one comparable number so we can rank a supplier
   against the others we track in its category and, when it's weak, name healthier
   backups to qualify as a second source. */
export function healthScore(d: Detail): number {
  let s = 50;
  const a = d.advanced;
  if (a?.fscore != null) s += (a.fscore - 4.5) * 4;               // Piotroski 0-9 → ±18
  if (d.score?.overall != null) s += ((d.score.overall as number) - 5) * 3; // Probe 0-10 → ±15
  if (a?.zZone === "distress") s -= 15; else if (a?.zZone === "safe") s += 4;
  const rt = d.creditRating;
  if (rt) { if (rt.flags.isDefault) s -= 25; else if (rt.flags.subInvestmentGrade) s -= 12; else if (rt.flags.inc) s -= 8; else if (rt.flags.strong) s += 10; }
  s -= d.levers.filter((l) => l.tone === "risk").length * 4;
  return Math.max(1, Math.min(100, Math.round(s)));
}
